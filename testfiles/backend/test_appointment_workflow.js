async function testAppointmentStatusUpdate(appointmentId) {
  console.log('\n📝 Testing Appointment Status Update...');
  
  if (!appointmentId) {
    logTest('Appointment Status Update - No Appointment ID', 'FAIL', {
      reason: 'No appointment ID provided from previous test'
    });
    return;
  }

  try {
    // Test approval
    const approvalResponse = await makeRequest('PUT', `${API_BASE_URL}/appointments/${appointmentId}/status`, {
      status: 'approved'
    });
    
    if (approvalResponse.statusCode === 200) {
      logTest('Appointment Status Update - Approval', 'PASS', {
        statusCode: approvalResponse.statusCode,
        appointmentId: appointmentId,
        newStatus: 'approved'
      });
    } else {
      logTest('Appointment Status Update - Approval', 'FAIL', {
        statusCode: approvalResponse.statusCode,
        response: approvalResponse.data
      });
    }

    // Test rejection
    const rejectionResponse = await makeRequest('PUT', `${API_BASE_URL}/appointments/${appointmentId}/status`, {
      status: 'rejected'
    });
    
    if (rejectionResponse.statusCode === 200) {
      logTest('Appointment Status Update - Rejection', 'PASS', {
        statusCode: rejectionResponse.statusCode,
        appointmentId: appointmentId,
        newStatus: 'rejected'
      });
    } else {
      logTest('Appointment Status Update - Rejection', 'FAIL', {
        statusCode: rejectionResponse.statusCode,
        response: rejectionResponse.data
      });
    }

    // Test invalid status
    const invalidStatusResponse = await makeRequest('PUT', `${API_BASE_URL}/appointments/${appointmentId}/status`, {
      status: 'invalid_status'
    });
    
    if (invalidStatusResponse.statusCode === 400) {
      logTest('Appointment Status Update - Invalid Status', 'PASS', {
        statusCode: invalidStatusResponse.statusCode,
        message: invalidStatusResponse.data.message || invalidStatusResponse.data.error
      });
    } else {
      logTest('Appointment Status Update - Invalid Status', 'FAIL', {
        statusCode: invalidStatusResponse.statusCode,
        expectedStatus: 400,
        response: invalidStatusResponse.data
      });
    }

  } catch (error) {
    logTest('Appointment Status Update - Error', 'FAIL', {
      error: error.message
    });
  }
}

