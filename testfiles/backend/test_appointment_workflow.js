// Utility function to make HTTP requests
function makeRequest(method, url, data = null) {
  return new Promise((resolve, reject) => {
    const urlObj = new URL(url);
    const options = {
      hostname: urlObj.hostname,
      port: urlObj.port,
      path: urlObj.pathname + urlObj.search,
      method: method,
      headers: {
        'Content-Type': 'application/json',
      }
    };

    const req = http.request(options, (res) => {
      let responseData = '';
      
      res.on('data', (chunk) => {
        responseData += chunk;
      });
      
      res.on('end', () => {
        try {
          const parsedData = responseData ? JSON.parse(responseData) : {};
          resolve({
            statusCode: res.statusCode,
            data: parsedData,
            headers: res.headers
          });
        } catch (error) {
          resolve({
            statusCode: res.statusCode,
            data: responseData,
            headers: res.headers
          });
        }
      });
    });

    req.on('error', (error) => {
      reject(error);
    });

    if (data) {
      req.write(JSON.stringify(data));
    }

    req.end();
  });
}

// Test results tracking
const testResults = {
  timestamp: new Date().toISOString(),
  tests: [],
  summary: {
    total: 0,
    passed: 0,
    failed: 0
  }
};

function logTest(testName, status, details) {
  const result = {
    testName,
    status,
    details,
    timestamp: new Date().toISOString()
  };
  
  testResults.tests.push(result);
  testResults.summary.total++;
  
  if (status === 'PASS') {
    testResults.summary.passed++;
    console.log(`✅ ${testName}: PASSED`);
  } else {
    testResults.summary.failed++;
    console.log(`❌ ${testName}: FAILED`);
    console.log(`   Details: ${JSON.stringify(details, null, 2)}`);
  }

  // Write results to file after each test
  fs.writeFileSync(TEST_RESULTS_FILE, JSON.stringify(testResults, null, 2));
}

// Get test data IDs from database
async function getTestDataIds() {
  console.log('\n🔍 Fetching test data IDs from database...');
  
  try {
    // Get test patient ID
    const patientResponse = await makeRequest('GET', `${API_BASE_URL.replace('/api', '')}/api/patients`);
    if (patientResponse.statusCode === 200 && patientResponse.data.length > 0) {
      const testPatient = patientResponse.data.find(p => p.uhid === 'TEST_PATIENT_001');
      if (testPatient) {
        testPatientId = testPatient._id;
        console.log(`   Patient ID: ${testPatientId}`);
      }
    }

    // Get test doctor ID  
    const doctorResponse = await makeRequest('GET', `${API_BASE_URL}/doctors/hospital/${testHospitalId}`);
    if (doctorResponse.statusCode === 200 && doctorResponse.data.length > 0) {
      const testDoctor = doctorResponse.data.find(d => d.doctorId === 'DOC_TEST_001');
      if (testDoctor) {
        testDoctorId = testDoctor._id;
        console.log(`   Doctor ID: ${testDoctorId}`);
      }
    }

    console.log(`   Hospital ID: ${testHospitalId}`);
    return true;
  } catch (error) {
    console.log(`   ⚠️  Using fallback IDs due to error: ${error.message}`);
    return false;
  }
}

