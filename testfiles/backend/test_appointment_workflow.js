// Main test execution
async function runComprehensiveTests() {
  console.log('🚀 Starting Comprehensive Appointment Workflow Tests');
  console.log('================================================');
  console.log(`📊 Results will be saved to: ${TEST_RESULTS_FILE}`);
  
  // Test server connectivity first
  const serverConnected = await testServerConnectivity();
  
  if (!serverConnected) {
    console.log('\n❌ Server connectivity failed. Please ensure backend server is running on port 3000');
    return;
  }

  // Get test data IDs from database
  await getTestDataIds();

  // Run the test sequence
  const appointmentId = await testPatientAppointmentBooking();
  await testPatientAppointmentBookingValidation();
  await testDoctorAppointmentRetrieval();
  await testAppointmentStatusUpdate(appointmentId);
  await testPatientAppointmentHistory();

  // Final summary
  console.log('\n📊 Test Summary');
  console.log('===============');
  console.log(`Total Tests: ${testResults.summary.total}`);
  console.log(`Passed: ${testResults.summary.passed}`);
  console.log(`Failed: ${testResults.summary.failed}`);
  console.log(`Success Rate: ${((testResults.summary.passed / testResults.summary.total) * 100).toFixed(1)}%`);
  console.log(`\n📄 Detailed results saved to: ${TEST_RESULTS_FILE}`);

  if (testResults.summary.failed > 0) {
    console.log('\n❌ Some tests failed. Check the detailed results file for more information.');
    process.exit(1);
  } else {
    console.log('\n✅ All tests passed! The appointment workflow is working correctly.');
    process.exit(0);
  }
}

// Handle uncaught exceptions
process.on('uncaughtException', (error) => {
  console.error('❌ Uncaught Exception:', error);
  logTest('Uncaught Exception', 'FAIL', { error: error.message });
  process.exit(1);
});

process.on('unhandledRejection', (reason, promise) => {
  console.error('❌ Unhandled Rejection at:', promise, 'reason:', reason);
  logTest('Unhandled Rejection', 'FAIL', { reason: reason });
  process.exit(1);
});

// Run the tests
